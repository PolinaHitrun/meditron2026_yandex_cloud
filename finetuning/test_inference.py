print("Раскрытие аббревиатур...")
expanded_text = expand_abbreviations(test_text)

print("\nРаспознавание сущностей...\n")
print(f"{'НАЙДЕННЫЙ ТЕКСТ':<45} | {'КЛАСС (МЕТКА)':<25} | {'УВЕРЕННОСТЬ'}")
print("-" * 90)

# Разбиваем длинный текст на короткие предложения через razdel
for sentence in sentenize(expanded_text):
    text_chunk = sentence.text.strip()
    if not text_chunk:
        continue
        
    entities = ner_pipeline(text_chunk)
    
    for ent in entities:
        word = ent['word'].strip()
        label = ent['entity_group']
        score = ent['score']
        
        # Игнорируем слишком короткие мусорные срабатывания
        if len(word) > 1:
            print(f"{word:<45} | {label:<25} | {score:.4f}")